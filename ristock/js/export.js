/* =====================================================================
 * export.js — 지금 보고 있는 결과를 CSV 로 내려받기
 *
 * 엑셀에서 바로 열려야 하므로 다음 두 가지를 지킵니다.
 *   1) 맨 앞에 UTF-8 BOM(﻿) — 없으면 한글이 전부 깨져 보입니다
 *   2) 줄바꿈은 CRLF — 옛 엑셀에서 줄이 밀리지 않습니다
 *
 * 전역 `RiExport` 노출. 의존성 0.
 * ===================================================================== */

(function (전역) {
  'use strict';

  /** CSV 한 칸 — 쉼표·따옴표·줄바꿈이 있으면 큰따옴표로 감싸고 내부 따옴표는 두 번 씁니다.
   *  숫자로 보이는 문자열(예: 한국 티커 "005930")이 엑셀에서 5930 으로 바뀌지 않도록
   *  앞의 0 이 살아야 하는 칸은 호출부에서 `문자열칸()` 을 씁니다. */
  function 칸(값) {
    if (값 === null || 값 === undefined) return '';
    var s = String(값);
    if (/[",\r\n]/.test(s)) return '"' + s.replace(/"/g, '""') + '"';
    return s;
  }

  /** 엑셀이 숫자로 해석하면 안 되는 값(티커 등). `="005930"` 형태로 강제 문자열. */
  function 문자열칸(값) {
    if (값 === null || 값 === undefined || 값 === '') return '';
    return '="' + String(값).replace(/"/g, '""') + '"';
  }

  function 표만들기(행들) {
    return '﻿' + 행들.map(function (행) {
      return 행.map(function (c) {
        // 이미 `="..."` 로 감싼 칸은 그대로 둡니다.
        return (typeof c === 'string' && c.slice(0, 2) === '="') ? c : 칸(c);
      }).join(',');
    }).join('\r\n');
  }

  /** 브라우저에서 파일로 저장. (a[download] — 라이브러리 없이) */
  function 내려받기(파일명, 내용) {
    try {
      var blob = new Blob([내용], { type: 'text/csv;charset=utf-8;' });
      var url = URL.createObjectURL(blob);
      var a = document.createElement('a');
      a.href = url;
      a.download = 파일명;
      a.style.display = 'none';
      document.body.appendChild(a);
      a.click();
      setTimeout(function () {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      }, 1000);
      return true;
    } catch (e) {
      return false;
    }
  }

  function 안전한파일명(s) {
    return String(s || '결과').replace(/[\\/:*?"<>|\s]+/g, '_').slice(0, 60);
  }

  /** 내려받은 파일은 앱을 떠나 카톡·메일로 돌아다닙니다.
   *  화면 하단 고지가 따라가지 않으므로 파일 안에 한 줄로 박아 둡니다.
   *  (엔진이 만드는 엑셀 `excelout.py` 에도 같은 문장이 들어 있습니다) */
  var 고지문 = '본 자료는 공개 데이터를 기계적으로 집계한 스크리닝 참고자료일 뿐이며, ' +
    '투자 권유가 아닙니다. 투자 판단과 그 결과는 이용자 본인에게 있습니다.';

  function 고지붙이기(행들) {
    행들.push([]);
    행들.push(['※ ' + 고지문]);
    return 행들;
  }

  /* -------------------------------------------------------------
   * 1. 전략 결과 CSV
   *    결과 = RiStrategy.전략실행(...) 이 돌려준 객체
   * ----------------------------------------------------------- */
  var 전략머리 = ['시장', '뉴스섹터', '분석섹터', '순위', '티커', '기업명', '한글명',
    '시총순위', '총점', '기준점수', '미네르비니', '거래량비', '순익성장률',
    '모멘텀', '차트', '밸류', '재무', '수급', '호재'];

  function 전략행들(결과, 전략이름, 기준일) {
    var 행들 = [];
    행들.push(['Ri_Stock 전략 결과', 전략이름 || '', '기준일', 기준일 || '', '내려받은시각',
      new Date().toLocaleString('ko-KR')]);
    행들.push([]);
    행들.push(전략머리);

    ['한국', '미국'].forEach(function (시장) {
      var m = (결과 && 결과.시장 && 결과.시장[시장]) || null;
      if (!m) return;
      (m.섹터별 || []).forEach(function (블록) {
        (블록.종목 || []).forEach(function (s, i) {
          행들.push([
            시장, 블록.뉴스섹터, 블록.섹터, i + 1,
            문자열칸(s.티커), s.기업명, s.한글명,
            s.시총순위, s.총점, s.기준점수, s.미네르비니,
            s.거래량비, s.순익성장률,
            s.모멘텀, s.차트, s.밸류, s.재무, s.수급, s.호재
          ]);
        });
      });
    });

    if (행들.length === 3) 행들.push(['(조건을 통과한 종목이 없습니다)']);
    return 고지붙이기(행들);
  }

  function 전략CSV(결과, 전략이름, 기준일) {
    var 파일명 = 'Ri_Stock_' + 안전한파일명(전략이름) + '_' + (기준일 || '') + '.csv';
    return 내려받기(파일명, 표만들기(전략행들(결과, 전략이름, 기준일)));
  }

  /* -------------------------------------------------------------
   * 2. 종목 목록 CSV — 13항목 점수와 주요 지표를 전부 담습니다
   * ----------------------------------------------------------- */
  var 점수항목 = ['모멘텀', '차트', 'ROE', '매출성장', '순익성장', '시총', '재무',
    '52주', '저변동', '밸류', '배당', '뉴스', '수급'];
  var 지표항목 = ['PER', 'PBR', 'ROE', '배당수익률', '부채비율', '모멘텀12M',
    '거래량비', '순익성장률', '고점대비', '10일고점비'];

  function 종목CSV(종목들, 시장, 기준일, 제목) {
    var 행들 = [];
    행들.push(['Ri_Stock 종목 목록', 제목 || 시장, '기준일', 기준일 || '', '종목수', (종목들 || []).length,
      '내려받은시각', new Date().toLocaleString('ko-KR')]);
    행들.push([]);
    행들.push(['시총순위', '티커', '기업명', '한글명', '섹터', '산업', '거래소', '시총(조원)',
      '평가', '총점']
      .concat(점수항목.map(function (k) { return '점수:' + k; }))
      .concat(지표항목.map(function (k) { return '지표:' + k; }))
      .concat(['미네르비니', '호재', '악재']));

    (종목들 || []).forEach(function (s) {
      var 점수 = s.점수 || {};
      var 지표 = s.지표 || {};
      행들.push([
        s.시총순위, 문자열칸(s.티커), s.기업명, s.한글명, s.섹터, s.산업, s.거래소, s.시총조원,
        s.평가 ? 'O' : 'X', s.평가 ? s.총점 : ''
      ]
        .concat(점수항목.map(function (k) { return s.평가 ? 점수[k] : ''; }))
        .concat(지표항목.map(function (k) { return 지표[k]; }))
        .concat([s.미네르비니, s.호재, s.악재]));
    });

    고지붙이기(행들);
    var 파일명 = 'Ri_Stock_종목_' + 안전한파일명(제목 || 시장) + '_' + (기준일 || '') + '.csv';
    return 내려받기(파일명, 표만들기(행들));
  }

  /* ----------------------------------------------------------- */
  전역.RiExport = {
    전략CSV: 전략CSV,
    종목CSV: 종목CSV,
    표만들기: 표만들기,
    전략행들: 전략행들,
    내려받기: 내려받기,
    버전: '1.0.0'
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
