# -*- coding: utf-8 -*-
"""Ri_Stock 수집 엔진 — 지수 시황 (코스피·코스닥·S&P500·나스닥)

**왜 만들었나 (2026-07-28)**

이 날 코스피는 −10.8%, 코스닥은 −7.7% 빠지고 서킷브레이커까지 걸렸는데,
앱의 '오늘의 시장 분위기'는 `중립·혼조` 라고 표시했습니다.
분위기를 **10개국 뉴스 건수의 호재/악재 비율만으로** 정했기 때문입니다.
뉴스는 하루 종일 고르게 쌓이지만 지수는 그날 하루에 다 반영됩니다 —
그래서 폭락한 날에도 뉴스 건수는 평소와 비슷하게 나옵니다.

지수는 **국내 소스(FinanceDataReader)** 에서 받습니다. 사장님 지시대로
국내 시장은 국내 자료로 봅니다. 야후를 거치지 않으므로 인증서·해외 IP 문제와도 무관합니다.

**신뢰 원칙**: 값을 지어내지 않습니다. 못 받은 지수는 목록에서 빠지고,
받은 지수에는 **그 값이 어느 날짜의 종가인지** 함께 적습니다.
07:00 회차처럼 한국 장이 열리기 전이면 코스피는 어제 종가가 담기는데,
날짜를 같이 보여 주면 화면에서 그것이 드러납니다.

import 시점에는 네트워크를 쓰지 않습니다(호출은 함수 안에서만).
"""

import time

# (시장, 이름, FinanceDataReader 코드)
지수목록 = [
    ('한국', '코스피', 'KS11'),
    ('한국', '코스닥', 'KQ11'),
    ('미국', 'S&P500', 'US500'),
    ('미국', '나스닥', 'IXIC'),
]

# 이 정도 떨어지면 '급락'으로 봅니다 (화면 경고 기준과 같은 값 — 설계서 2.3)
급락기준 = -3.0
급등기준 = 3.0


def _한줄(코드, 이름, 시장, 시작일):
    import FinanceDataReader as fdr

    df = fdr.DataReader(코드, 시작일)
    if df is None or len(df) < 2 or 'Close' not in df:
        return None
    종가 = float(df['Close'].iloc[-1])
    전일 = float(df['Close'].iloc[-2])
    if not 종가 or not 전일:
        return None
    return {
        '시장': 시장,
        '이름': 이름,
        '코드': 코드,
        '날짜': df.index[-1].strftime('%Y%m%d'),
        '종가': round(종가, 2),
        '등락률': round((종가 / 전일 - 1) * 100, 2),
    }


def collect_indices(시작일=None):
    """지수 4종의 최근 종가·전일대비 등락률 (설계서 2.3 `market.json.지수`).

    한 종목이 실패해도 나머지는 그대로 담습니다. 전부 실패하면 목록이 빕니다.
    예외를 밖으로 던지지 않습니다 — 지수를 못 받았다고 회차 전체를 죽일 일은 아닙니다.
    """
    if 시작일 is None:
        # 휴장·연휴를 넉넉히 건너뛰려고 30일치를 받습니다(전일 종가만 있으면 됩니다).
        시작일 = time.strftime('%Y-%m-%d', time.localtime(time.time() - 30 * 86400))

    목록, 실패 = [], []
    for 시장, 이름, 코드 in 지수목록:
        try:
            행 = _한줄(코드, 이름, 시장, 시작일)
        except Exception:
            행 = None
        if 행:
            목록.append(행)
        else:
            실패.append(이름)
    if 실패:
        print(f'  (참고) 지수 수집 실패: {", ".join(실패)}')
    # `급락기준` 을 파일에 함께 담습니다 — 화면(app.js)이 이 값을 읽어 경고를 띄웁니다.
    # 양쪽에 숫자를 따로 적어 두면 한쪽만 고쳤을 때 조용히 갈라집니다.
    return {'수집시각': time.strftime('%Y-%m-%d %H:%M'), '목록': 목록,
            '실패': 실패, '급락기준': 급락기준}


def 시장별평균(지수, 시장):
    """해당 시장 지수들의 평균 등락률 — 없으면 None."""
    값 = [x['등락률'] for x in ((지수 or {}).get('목록') or [])
          if x.get('시장') == 시장 and x.get('등락률') is not None]
    return round(sum(값) / len(값), 2) if 값 else None


def 지수문구(지수, 시장=None):
    """'코스피 6,023.66 (-10.8%) · 코스닥 705.85 (-7.7%)' 같은 한 줄 — 없으면 빈 문자열."""
    조각 = []
    for x in ((지수 or {}).get('목록') or []):
        if 시장 and x.get('시장') != 시장:
            continue
        부호 = '+' if x['등락률'] > 0 else ''
        조각.append(f"{x['이름']} {x['종가']:,.2f} ({부호}{x['등락률']:.1f}%)")
    return ' · '.join(조각)


def 기준날짜(지수, 시장):
    """그 시장 지수가 **어느 날 종가**인지 'MM.DD' — 없으면 빈 문자열.

    07:00 회차에는 한국 장이 열리기 전이라 코스피가 어제 종가입니다.
    날짜를 함께 보여 주지 않으면 어제 값을 오늘 것으로 읽게 됩니다(신뢰 우선).
    """
    for x in ((지수 or {}).get('목록') or []):
        if x.get('시장') == 시장 and x.get('날짜'):
            d = str(x['날짜'])
            return f'{d[4:6]}.{d[6:8]}' if len(d) == 8 else d
    return ''
