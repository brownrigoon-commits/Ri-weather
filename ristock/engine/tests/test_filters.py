# -*- coding: utf-8 -*-
"""필터 8종 경계값 검증 (설계서 3.1)

여기가 새 엔진에서 **가장 크게 달라진 부분**입니다.
옛 대시보드는 `'고점대비 92%'` 같은 한글 문장을 정규식으로 파싱해 필터에 썼습니다.
문장이 조금만 바뀌면 정규식이 `None` 을 돌려주고, 전략이 조용히 빈 결과를 냈습니다.
이제 `지표.고점대비` · `지표.10일고점비` 숫자만 봅니다.

그래서 **null(값 없음) 처리**가 곧 이 필터들의 안전선입니다.
7/15 분석표처럼 컬럼 자체가 없던 날에도 "빈 값 = 통과" 로 새어 나가면 안 됩니다.
아래 표를 한 칸씩 다 덮습니다.

| 키 | 통과 | 탈락 |
|---|---|---|
| 악재제외 | 악재 빈 문자열/공백/없음 | 악재 문장 있음 |
| 흑자만 | 근거.재무 에 '흑자' | '적자' · 근거 없음 |
| 눌림만 | '눌림' 포함 & '미눌림' 으로 시작 안 함 | '미눌림…' · 눌림 없음 |
| 전고점돌파만 | 고점대비 ≥ 85 & 10일고점비 > 0 | 84.9 · 0 · 음수 · **둘 중 하나라도 null** |
| 미네르비니만 | 'O' | 'X' · '' · null |
| 거래량150이상 | ≥ 150 | 149.9 · 0 · **null** |
| 순익성장25이상 | ≥ 25 | 24.9 · 음수 · **null** |
| 신고가근접만 | ≥ 75 | 74.9 · **null** |

    실행: python -m pytest ristock/engine/tests/test_filters.py -q
"""

import pytest

from ristock.engine import strategies as S


def 종목(악재='', 재무='부채 30%, 흑자', 차트='1차 눌림(MA20 근접), 10일고점比 -3.2%, 정배열',
        미네르비니='O', 거래량비=200.0, 순익성장률=30.0, 고점대비=90.0, 십일고점비=1.5,
        **덮어쓰기):
    """기본값은 **모든 필터를 통과하는** 종목입니다. 검사하려는 값 하나만 바꿔 씁니다."""
    레코드 = {
        '티커': 'TEST', '기업명': '테스트', '평가': True, '총점': 70.0,
        '점수': {'차트': 10.0, '모멘텀': 7.5},
        '근거': {'재무': 재무, '차트': 차트, '52주': '고점대비 90%'},
        '지표': {'거래량비': 거래량비, '순익성장률': 순익성장률,
                '고점대비': 고점대비, '10일고점비': 십일고점비,
                'PER': 12.3, 'ROE': 9.8},
        '미네르비니': 미네르비니,
        '악재': 악재,
    }
    레코드.update(덮어쓰기)
    return 레코드


모든필터 = ['악재제외', '흑자만', '눌림만', '전고점돌파만', '미네르비니만',
          '거래량150이상', '순익성장25이상', '신고가근접만']


# ---------------------------------------------------------------------
# 0. 기본 동작
# ---------------------------------------------------------------------
def test_필터가_비어있으면_전부_통과():
    assert S.통과여부(종목(악재='[분식회계] 조사 착수', 재무='적자'), {}) is True
    assert S.통과여부(종목(), None) is True


def test_필터값이_거짓이면_그_조건은_검사하지_않는다():
    """`전고점뚤고` 전략의 `눌림만: false` 처럼, 꺼 둔 필터는 없는 것과 같아야 합니다."""
    미눌림종목 = 종목(차트='미눌림(정배열)')
    assert S.통과여부(미눌림종목, {'눌림만': False}) is True
    assert S.통과여부(미눌림종목, {'눌림만': True}) is False


def test_기본종목은_8개_필터를_모두_통과한다():
    assert S.통과여부(종목(), {k: True for k in 모든필터}) is True


def test_필터는_AND다_하나만_틀려도_탈락():
    assert S.통과여부(종목(순익성장률=10.0), {'악재제외': True, '흑자만': True}) is True
    assert S.통과여부(종목(순익성장률=10.0),
                    {'악재제외': True, '순익성장25이상': True}) is False


