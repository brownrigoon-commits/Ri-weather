# 9. 실제 전략 정의로 확인 — strategies.json 의 필터 조합이 그대로 먹히는가
# ---------------------------------------------------------------------
def test_전고점뚤고_필터조합(전략정의):
    전략 = next(s for s in 전략정의['전략'] if s['id'] == '전고점뚤고')
    필터 = 전략['filters']
    assert 필터 == {'악재제외': True, '흑자만': True, '눌림만': False, '전고점돌파만': True}
    # 눌림만이 꺼져 있으므로 미눌림 종목도 통과해야 한다
    assert S.통과여부(종목(차트='미눌림(정배열)'), 필터) is True
    assert S.통과여부(종목(차트='미눌림(정배열)', 십일고점비=-1.0), 필터) is False


def test_triple_필터조합은_세_조건_모두_필요(전략정의):
    전략 = next(s for s in 전략정의['전략'] if s['id'] == 'triple')
    필터 = 전략['filters']
    assert S.통과여부(종목(), 필터) is True
    assert S.통과여부(종목(미네르비니='X'), 필터) is False
    assert S.통과여부(종목(십일고점비=-0.1), 필터) is False
    assert S.통과여부(종목(거래량비=100.0), 필터) is False
    assert S.통과여부(종목(악재='[리콜] 전량 회수'), 필터) is False


def test_canslim_필터조합(전략정의):
    전략 = next(s for s in 전략정의['전략'] if s['id'] == 'canslim')
    필터 = 전략['filters']
    assert 필터 == {'순익성장25이상': True, '신고가근접만': True,
                  '흑자만': True, '악재제외': True}
    assert S.통과여부(종목(고점대비=75.0, 순익성장률=25.0), 필터) is True
    assert S.통과여부(종목(고점대비=74.9, 순익성장률=25.0), 필터) is False
    assert S.통과여부(종목(고점대비=75.0, 순익성장률=None), 필터) is False


def test_필터설명이_필터_8개를_모두_설명한다(전략정의):
    """화면에 띄울 설명이 빠지면 사장님이 토글의 뜻을 알 수 없습니다(설계서 2.4)."""
    assert set(전략정의['필터설명']) == set(모든필터)
    assert all(전략정의['필터설명'][k].strip() for k in 모든필터)


def test_전략정의의_필터키가_모두_구현되어_있다(전략정의):
    """strategies.json 에 오타난 필터 키가 있으면 조용히 무시되어 결과가 헐거워집니다."""
    쓰인키 = {k for s in 전략정의['전략'] for k in (s.get('filters') or {})}
    assert 쓰인키 <= set(모든필터), f'구현되지 않은 필터 키: {쓰인키 - set(모든필터)}'


def test_전략정의의_순위기준이_모두_구현되어_있다(전략정의):
    """`rank_by` 가 오타나면 `점수.<오타>` 가 전부 None → 0 이 되어 입력 순서대로 나갑니다."""
    허용 = {'총점', '차트', '모멘텀', '전고점', '마법공식'}
    for s in 전략정의['전략']:
        assert s.get('rank_by', '총점') in 허용, f"{s['id']} 의 rank_by={s.get('rank_by')}"
