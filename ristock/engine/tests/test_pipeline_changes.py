# =====================================================================
# 기준선이 망가졌을 때 — **손상이 굳어 버리면 안 된다**
# =====================================================================
#   JSON 자체가 깨지면 `load_picks_baseline` 이 빈 dict 를 돌려주어 그 회차가 기준선을
#   새로 만들고 다음 날부터 정상으로 돌아옵니다. 그런데 파일이 **반쯤만** 망가지면
#   (`대기` 나 `전략별` 한 칸의 타입이 어긋나면) 예외가 나고, 그 예외 때문에
#   기준선을 다시 쓰지 못해 **손상이 영원히 굳습니다** — 사람이 파일을 지울 때까지
#   '어제 대비 변화' 카드가 다시는 안 뜹니다. 통째로 깨진 것보다 나쁜 상태입니다.
망가뜨리기 = [
    ('깨진 JSON', '{"기준일": "202607'),
    ('빈 파일', ''),
    ('dict 가 아님', '[1, 2, 3]'),
    ('대기가 문자열', '{"기준일": "20260715", "전략별": {}, "대기": "xxx"}'),
    ('전략별이 리스트', '{"기준일": "20260715", "전략별": ["total"],'
                  ' "시장기준일": {"한국": "20260715"}}'),
    ('전략별[id] 가 리스트', '{"기준일": "20260715", "전략별": {"total": ["005930"]},'
                       ' "시장기준일": {"한국": "20260715", "미국": "20260715"}}'),
    ('시장기준일이 리스트', '{"기준일": "20260715", "전략별": {"total": {"한국": []}},'
                    ' "시장기준일": ["한국"]}'),
]


@pytest.mark.parametrize('이름,내용', 망가뜨리기, ids=[n for n, _ in 망가뜨리기])
def test_기준선이_망가져도_그_회차가_새로_만들어_손상이_굳지_않는다(monkeypatch, 작업폴더,
                                                     하루치, 이름, 내용):
    회차실행(monkeypatch, 작업폴더, 일차1, 하루치[일차1])
    기준선경로 = os.path.join(str(작업폴더), emit.PICKS_BASELINE_FILE)
    with open(기준선경로, 'w', encoding='utf-8') as f:
        f.write(내용)

    코드 = 회차실행(monkeypatch, 작업폴더, 일차2, 하루치[일차2])          # 죽지 않아야 하고
    assert 코드 == 0

    기준선 = 읽기(작업폴더, emit.PICKS_BASELINE_FILE)                    # 다시 쓰여야 한다
    assert isinstance(기준선, dict) and 기준선['대기']['기준일'] == 일차2, \
        f'{이름}: 손상된 기준선을 그대로 두면 어제 대비 변화가 영영 안 나옵니다'
    m = 읽기(작업폴더, MANIFEST_FILE)
    assert '변화 계산 실패' not in (m.get('실행', {}).get('메모') or ''), \
        f'{이름}: 예외로 끝내지 말고 기준선을 새로 만들어야 합니다'

    # 그리고 **다음 날**에는 정상으로 돌아와야 한다
    회차실행(monkeypatch, 작업폴더, 일차3, 하루치[일차1])
    변화 = 읽기(작업폴더, emit.CHANGES_FILE)
    assert 변화 and 변화['이전기준일'] == 일차2, f'{이름}: 다음 날 복구되지 않았습니다'


