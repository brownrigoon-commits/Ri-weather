# 수집기만 얼린 pipeline 실행 — 네트워크는 한 번도 쓰지 않습니다
# =====================================================================
def _스냅샷쓰기(스냅샷, market, out_dir, 기준일, 생성시각, 원본='', 차트=None):
    """`emit.write_stocks` 자리에 끼워 넣는 가짜 — 픽스처 스냅샷을 그날 날짜로 저장합니다.

    실제 엔진은 DataFrame 을 받아 종목 레코드를 만들지만, 여기서 검증할 것은
    **변화 계산**이지 레코드 생성이 아닙니다. 그 부분은 `test_emit_total_parity.py`
    와 `test_strategies_golden.py` 가 이미 지키고 있습니다.
    """
    payload = dict(스냅샷)
    payload.update(시장=market, 기준일=기준일, 생성시각=생성시각, 원본=원본)
    경로 = os.path.join(out_dir, STOCKS_FILE[market])
    emit.write_json(경로, payload)
    종목 = payload.get('종목') or []
    return 경로, len(종목), sum(1 for s in 종목 if s.get('평가'))


def 회차실행(monkeypatch, out, 기준일, 스냅샷, 실패시장=(), 인자=()):
    """하루치 실행 한 번. `스냅샷` = {'한국': …, '미국': …} (그날 수집기가 돌려줄 값)"""
    with monkeypatch.context() as mp:
        mp.setattr(pipeline, '_today', lambda: 기준일)
        mp.setattr(pipeline, '_now', lambda: f'{기준일[:4]}-{기준일[4:6]}-{기준일[6:]} 16:30')
        mp.setattr(emit, 'write_stocks', _스냅샷쓰기)

        def 수집기(시장):
            def runner(top_n, sample, no_news, excel_dir, skip_excel,
                       retry=None, backoff=None):
                if 시장 in 실패시장:
                    raise RuntimeError(f'{시장} 수집 실패(모의)')
                # 수집기는 (DataFrame, 엑셀파일명, 차트) 를 돌려줍니다.
                # 차트(설계서 2.2)는 그래프용 부가 정보라 여기서는 비워 둡니다.
                return 스냅샷[시장], '', {}
            return runner

        mp.setattr(pipeline, 'RUNNERS',
                   {'us': ('미국', 수집기('미국')), 'kr': ('한국', 수집기('한국'))})
        return pipeline.main(['--market', 'all', '--out', str(out),
                              '--skip-excel', '--no-news', '--no-market-news']
                             + list(인자))


def 읽기(out, 이름):
    return emit.load_json(os.path.join(str(out), 이름))


def 있음(out, 이름):
    return os.path.exists(os.path.join(str(out), 이름))


