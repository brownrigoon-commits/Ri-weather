# 옛 구현(스냅샷 두 벌을 통째로 비교) — 대조용 기준값
# ---------------------------------------------------------------------
def 옛방식변화(오늘스냅, 이전스냅, 시장요약, 전략정의, 기준일, 이전기준일):
    """archive 를 쓰던 시절의 `pipeline.변화쓰기()` 계산을 그대로 재현합니다."""
    전략목록 = 전략정의['전략']
    섹터매핑 = 전략정의.get('섹터매핑') or {}
    오늘결과 = S.전체전략실행(
        전략목록, {m: S.시장준비(s) for m, s in 오늘스냅.items()}, 시장요약, 섹터매핑)
    이전결과 = S.전체전략실행(
        전략목록, {m: S.시장준비(s) for m, s in 이전스냅.items()}, 시장요약, 섹터매핑)
    변화 = S.변화계산(오늘결과, 이전결과, 기준일, 이전기준일)
    for 시장별 in (변화.get('전략별') or {}).values():        # 갱신 안 된 시장 제거
        for 시장 in list(시장별):
            if 시장 not in 오늘스냅:
                del 시장별[시장]
    return 변화


