def test_나_이튿날_changes_는_옛구현과_한글자도_같다(monkeypatch, 작업폴더, 하루치,
                                                시장요약, 전략정의):
    회차실행(monkeypatch, 작업폴더, 일차1, 하루치[일차1])
    회차실행(monkeypatch, 작업폴더, 일차2, 하루치[일차2])

    변화 = 읽기(작업폴더, emit.CHANGES_FILE)
    기대 = 옛방식변화(하루치[일차2], 하루치[일차1], 시장요약, 전략정의, 일차2, 일차1)
    assert 변화 == 기대, 'archive 를 쓰던 시절과 결과가 달라지면 안 됩니다'

    # 규격(설계서 2.5)과 manifest 키(js/data.js 계약)는 그대로여야 합니다
    assert 변화['기준일'] == 일차2 and 변화['이전기준일'] == 일차1
    for 시장별 in 변화['전략별'].values():
        for 시장, 값 in 시장별.items():
            assert 시장 in ('한국', '미국')
            assert isinstance(값['신규'], list) and isinstance(값['이탈'], list)
    m = 읽기(작업폴더, MANIFEST_FILE)
    assert m['변화파일'] == emit.CHANGES_FILE and m['이전기준일'] == 일차1

    # 비교가 실제로 무언가를 잡아냈는가 (전부 빈 결과면 위 비교는 아무것도 증명하지 못합니다)
    신규수 = sum(len(v['신규']) for 시장별 in 변화['전략별'].values()
              for v in 시장별.values())
    assert 신규수 > 0


