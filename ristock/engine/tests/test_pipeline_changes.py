def test_가_첫날은_기준선만_만들고_changes_는_없다(monkeypatch, 작업폴더, 하루치):
    코드 = 회차실행(monkeypatch, 작업폴더, 일차1, 하루치[일차1])
    assert 코드 == 0

    assert 있음(작업폴더, emit.PICKS_BASELINE_FILE), '기준선이 만들어져야 합니다'
    assert not 있음(작업폴더, emit.CHANGES_FILE), \
        '비교할 어제가 없는데 changes.json 을 만들면 첫날 화면이 통째로 신규처럼 보입니다'

    m = 읽기(작업폴더, MANIFEST_FILE)
    assert '변화파일' not in m and '이전기준일' not in m, \
        'manifest 가 없는 파일을 가리키면 앱이 404 를 받습니다(js/data.js 변화파일명)'

    기준선 = 읽기(작업폴더, emit.PICKS_BASELINE_FILE)
    assert 기준선['대기']['기준일'] == 일차1
    assert set(기준선['대기']['시장기준일']) == {'한국', '미국'}


def test_가_기준선은_스냅샷이_아니라_티커목록만_담는다(monkeypatch, 작업폴더, 하루치):
    """0.6MB 스냅샷을 대신하는 파일이므로 **작아야** 의미가 있습니다."""
    회차실행(monkeypatch, 작업폴더, 일차1, 하루치[일차1])
    크기 = os.path.getsize(os.path.join(str(작업폴더), emit.PICKS_BASELINE_FILE))
    assert 크기 < 60 * 1024, f'기준선이 {크기 / 1024:.1f}KB — 티커 목록만 담아야 합니다'

    담긴것 = 읽기(작업폴더, emit.PICKS_BASELINE_FILE)['대기']['전략별']
    표본 = 담긴것['total']['한국'][0]
    assert set(표본) == {'티커', '기업명', '섹터'}, '점수·근거까지 들고 있으면 안 됩니다'


