"""전일 대비 변화(changes.json)를 `picks_baseline.json` 하나로 계산하는가

**왜 이 파일이 있는가**

예전에는 어제 스냅샷 **전체**(stocks_KR/US.json ≈ 0.6MB)를 비교 대상으로 삼아
`ristock/data/archive/YYYYMMDD/` 에 남기고 매 회차 통째로 커밋했습니다.
git 이력은 append-only 라 나중에 지워도 영원히 남습니다 → 연 40MB 씩 저장소가 무거워지고,
집·회사 두 PC 가 매번 clone·pull 하는 사장님 워크플로가 그대로 느려집니다.

변화 계산에 정말 필요한 것은 **전략이 뽑은 티커 목록**(≈10KB)뿐입니다.
그래서 `picks_baseline.json` 하나만 두고 비교합니다(설계서 2.6).

여기서는 **수집기만 얼린 채 `pipeline.main()` 을 실제로 돌려** 세 가지를 확인합니다.

    (가) 1일차          → 기준선만 생기고 changes.json 은 만들지 않는다
    (나) 2일차          → changes.json 이 나오고, 내용이 **옛 구현과 한 글자도 다르지 않다**
    (다) 같은 날 2회차  → 아침 실행분이 아니라 **어제와 비교**한다  ← 이번 개선의 핵심

    실행: python -m pytest ristock/engine/tests/test_pipeline_changes.py -q
"""

