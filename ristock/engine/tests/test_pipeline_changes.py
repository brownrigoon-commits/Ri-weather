def test_한쪽_시장만_돈_회차도_다른_시장의_변화를_지우지_않는다(monkeypatch, 작업폴더,
                                                  하루치, 시장요약, 전략정의):
    """CI 는 `--market us` 와 `--market kr` 를 따로 돕니다.

    나중 회차가 자기 시장만 담은 changes.json 으로 덮어쓰면, 아침에 계산해 둔
    다른 시장의 변화가 화면에서 사라집니다.
    """
    회차실행(monkeypatch, 작업폴더, 일차1, 하루치[일차1])
    with monkeypatch.context() as mp:            # 미국만 도는 회차
        mp.setattr(pipeline, '_today', lambda: 일차2)
        mp.setattr(emit, 'write_stocks', _스냅샷쓰기)
        mp.setattr(pipeline, 'RUNNERS', {
            'us': ('미국', lambda *a, **k: (하루치[일차2]['미국'], '', {})),
            'kr': ('한국', lambda *a, **k: (하루치[일차2]['한국'], '', {}))})
