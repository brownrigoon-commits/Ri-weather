def test_대기는_날짜가_바뀔_때만_승격된다():
    기준선 = {'기준일': '20260715', '전략별': {'total': {'한국': [], '미국': []}},
            '시장기준일': {'한국': '20260715', '미국': '20260715'},
            '대기': {'기준일': '20260716',
                    '전략별': {'total': {'한국': [{'티커': '005930'}]}},
                    '시장기준일': {'한국': '20260716'}}}

    그대로 = emit.기준선승격(기준선, '20260716')          # 같은 날 두 번째 회차
    assert 그대로['기준일'] == '20260715' and 그대로['대기']['기준일'] == '20260716'

    올라감 = emit.기준선승격(기준선, '20260717')          # 다음 날
    assert 올라감['기준일'] == '20260716'
    assert '대기' not in 올라감
    assert 올라감['전략별']['total']['한국'] == [{'티커': '005930'}]
    assert 올라감['시장기준일'] == {'한국': '20260716', '미국': '20260715'}, \
        '대기에 없던 미국은 옛 기준을 그대로 지켜야 합니다'


