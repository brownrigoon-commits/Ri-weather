const 케이스결과 = [];

function 정답지케이스() {
  for (const 전략 of 전략목록) {
    const 정답 = 읽기(픽스처(정답지파일[전략.id]));

    // 이 전략이 실제로 읽었던 분석표로 시장 데이터를 맞춘다
    const 시장데이터 = {};
    for (const 시장이름 of ['한국', '미국']) {
      const 파일 = 정답['시장'][시장이름]['파일'];
      const 스냅 = 스냅샷(파일);
      if (스냅['원본'] !== 파일) {
        throw new Error(`스냅샷 짝이 어긋났습니다: ${시장이름} 정답지=${파일} 스냅샷=${스냅['원본']}`);
      }
      시장데이터[시장이름] = 스냅;
    }

    const 결과 = RiStrategy.전략실행({
      전략, 시장데이터, 시장요약, 섹터매핑전체
    });

    for (const 시장이름 of ['한국', '미국']) {
      const 어긋남 = [];
      const 기대시장 = 정답['시장'][시장이름];
      const 실제시장 = 결과['시장'][시장이름];

      // (1) 전략 공통 값
      if (JSON.stringify(결과['뉴스섹터']) !== JSON.stringify(정답['뉴스섹터'])) {
        어긋남.push(`뉴스섹터: 우리=${JSON.stringify(결과['뉴스섹터'])} 정답지=${JSON.stringify(정답['뉴스섹터'])}`);
      }
      if (결과['기준날짜'] !== 정답['기준날짜']) {
        어긋남.push(`기준날짜: 우리=${결과['기준날짜']} 정답지=${정답['기준날짜']}`);
      }

      // (2) 어느 분석표를 언제 읽었는가
      if (실제시장['파일'] !== 기대시장['파일']) {
        어긋남.push(`파일: 우리=${실제시장['파일']} 정답지=${기대시장['파일']}`);
      }
      if (실제시장['수정시각'] !== 기대시장['수정시각']) {
        어긋남.push(`수정시각: 우리=${실제시장['수정시각']} 정답지=${기대시장['수정시각']}`);
      }

      // (3) 블록(뉴스섹터 → 분석섹터) 구성
      const 기대블록 = 기대시장['섹터별'] || [];
      const 실제블록 = 실제시장['섹터별'] || [];
      if (실제블록.length !== 기대블록.length) {
        어긋남.push(`블록 수: 우리=${실제블록.length} 정답지=${기대블록.length} ` +
          `(우리 ${JSON.stringify(실제블록.map(b => b['섹터']))} / ` +
          `정답지 ${JSON.stringify(기대블록.map(b => b['섹터']))})`);
      }

      const 블록수 = Math.min(기대블록.length, 실제블록.length);
      let 종목수 = 0;
      for (let i = 0; i < 블록수; i++) {
        const 기대b = 기대블록[i], 실제b = 실제블록[i];
        const 위치 = `블록${i + 1}`;
        if (실제b['뉴스섹터'] !== 기대b['뉴스섹터']) {
          어긋남.push(`${위치}.뉴스섹터: 우리=${실제b['뉴스섹터']} 정답지=${기대b['뉴스섹터']}`);
        }
        if (실제b['섹터'] !== 기대b['섹터']) {
          어긋남.push(`${위치}.섹터: 우리=${실제b['섹터']} 정답지=${기대b['섹터']}`);
        }
        const 기대종목 = 기대b['종목'] || [];
        const 실제종목 = 실제b['종목'] || [];
        종목수 += 기대종목.length;

        // 종목 순서 — 티커 나열을 먼저 비교해야 어긋난 이유가 보인다
        const 기대티커 = JSON.stringify(기대종목.map(s => s['티커']));
        const 실제티커 = JSON.stringify(실제종목.map(s => s['티커']));
        if (기대티커 !== 실제티커) {
          어긋남.push(`${위치} 종목 순서: 우리=${실제티커} 정답지=${기대티커}`);
        }
        const n = Math.min(기대종목.length, 실제종목.length);
        for (let k = 0; k < n; k++) {
          종목대조(기대종목[k], 실제종목[k], `${위치}[${k + 1}] ${기대종목[k]['티커']}`, 어긋남);
        }
      }

      케이스결과.push({
        이름: `${전략.id} / ${시장이름}`,
        메모: `블록 ${기대블록.length} · 종목 ${종목수} · ${기대시장['파일']}`,
        어긋남
      });
    }
  }
}

