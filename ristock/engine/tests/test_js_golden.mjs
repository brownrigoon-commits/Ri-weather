/* ---------------------------------------------------------------
 * 2. 비교 도우미 — 정답지에 있는 값은 하나도 빠짐없이 대조
 * ------------------------------------------------------------- */
function 값표기(v) {
  return typeof v === 'string' ? JSON.stringify(v) : String(v);
}

function 같은값(a, b) {
  if (a === null || b === null) return a === b;
  if (typeof a === 'number' && typeof b === 'number') return Object.is(a, b);
  return a === b;
}

/** 정답지 종목 카드 하나를 통째로 대조.
 *  7/15 정답지에는 `미네르비니`·`거래량비`·`순익성장률` 칸이 없습니다(옛 대시보드 버전 차이).
 *  그래서 **정답지에 있는 키는 전부** 검사하고, 없는 키는 검사 대상에서 빠집니다. */
function 종목대조(기대, 실제, 위치, 어긋남) {
  for (const 키 of Object.keys(기대)) {
    if (!(키 in 실제)) {
      어긋남.push(`${위치}.${키}: 우리 결과에 이 칸이 없습니다 (정답지=${값표기(기대[키])})`);
      continue;
    }
    if (!같은값(기대[키], 실제[키])) {
      어긋남.push(`${위치}.${키}: 우리=${값표기(실제[키])} 정답지=${값표기(기대[키])}`);
    }
  }
}

