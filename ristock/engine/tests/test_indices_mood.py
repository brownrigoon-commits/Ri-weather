# -*- coding: utf-8 -*-
"""지수 시황 — 시장 분위기가 **지수를 보고** 정해지는지 확인합니다.

2026-07-28 코스피는 −10.8%, 코스닥은 −7.7% 빠지고 서킷브레이커까지 걸렸는데
앱 화면에는 `중립·혼조 분위기` 가 떠 있었습니다. 분위기를 10개국 뉴스 건수의
호재/악재 비율만으로 정했기 때문입니다. 뉴스는 하루 종일 고르게 쌓이지만
지수는 그날 하루가 그대로 찍힙니다 — 그래서 폭락한 날에도 뉴스 건수는 평소와 비슷합니다.

네트워크는 쓰지 않습니다. 수집한 값을 넣었을 때 **무엇이라고 말하는지**만 봅니다.
"""
import pytest

from ristock.engine import emit, indices, news


def 지수(한국=None, 미국=None, 날짜='20260728'):
    목록 = []
    if 한국 is not None:
        목록 += [{'시장': '한국', '이름': '코스피', '코드': 'KS11',
                  '날짜': 날짜, '종가': 6023.66, '등락률': 한국},
                 {'시장': '한국', '이름': '코스닥', '코드': 'KQ11',
                  '날짜': 날짜, '종가': 705.85, '등락률': 한국}]
    if 미국 is not None:
        목록 += [{'시장': '미국', '이름': 'S&P500', '코드': 'US500',
                  '날짜': '20260727', '종가': 7413.18, '등락률': 미국}]
    return {'수집시각': '2026-07-28 22:13', '목록': 목록, '실패': [],
            '급락기준': indices.급락기준}


def test_폭락한_날_뉴스가_좋아도_급락이라고_말한다():
    """이번 사고의 재현 — 호재 뉴스가 훨씬 많아도 지수가 무너졌으면 급락입니다."""
    문장 = news.지수_반영_분위기(호재수=90, 악재수=20, 지수=지수(한국=-10.84, 미국=0.02))
    assert '국내 증시 급락' in 문장
    assert '중립' not in 문장 and '위험선호' not in 문장
    assert '코스피' in 문장 and '-10.8%' in 문장


@pytest.mark.parametrize('등락률, 기대', [
    (-10.84, '국내 증시 급락'),
    (-3.0, '국내 증시 급락'),      # 경계값 — 기준과 같으면 급락 쪽
    (-2.9, '국내 증시 약세'),
    (-1.0, '국내 증시 약세'),
    (-0.9, '국내 증시 보합'),
    (0.9, '국내 증시 보합'),
    (1.0, '국내 증시 강세'),
    (3.0, '국내 증시 급등'),
])
def test_등락률에_따른_판정(등락률, 기대):
    assert 기대 in news.지수_반영_분위기(50, 50, 지수(한국=등락률))


def test_지수를_못_받으면_예전처럼_뉴스로_정한다():
    """지수 수집이 실패한 날에도 화면이 비면 안 됩니다 — 예전 문구 그대로."""
    for 지수값 in (None, {}, {'목록': []}):
        assert news.지수_반영_분위기(90, 20, 지수값) == '전반적으로 위험선호(강세) 분위기입니다.'
        assert news.지수_반영_분위기(20, 90, 지수값) == '전반적으로 위험회피(약세) 분위기입니다.'
        assert news.지수_반영_분위기(50, 50, 지수값) == '전반적으로 중립·혼조 분위기입니다.'


def test_어느_날_종가인지_함께_말한다():
    """07:00 회차에는 한국 장 전이라 어제 종가가 담깁니다 — 날짜를 숨기면 오해합니다."""
    문장 = news.지수_반영_분위기(50, 50, 지수(한국=-1.5, 날짜='20260727'))
    assert '[07.27 종가]' in 문장


def test_급락기준은_파일에_함께_담긴다():
    """화면(app.js)이 이 값을 읽어 경고를 띄웁니다 — 양쪽에 따로 적으면 갈라집니다."""
    assert 지수(한국=-1)['급락기준'] == indices.급락기준 == -3.0


def test_시장별평균은_해당_시장만_센다():
    값 = 지수(한국=-10.0, 미국=5.0)
    assert indices.시장별평균(값, '한국') == -10.0
    assert indices.시장별평균(값, '미국') == 5.0
    assert indices.시장별평균({'목록': []}, '한국') is None


def test_manifest_시장칸에_수집주체가_남는다():
    """깃허브가 '오늘 한국은 국내 PC 가 받았다'를 알아야 양보할 수 있습니다."""
    칸 = emit.market_entry('stocks_KR.json', 300, 144, '한국_분석표.xlsx',
                           '2026-07-28 22:04', '20260728', 'pc')
    assert 칸['수집주체'] == 'pc'
    assert 칸['기준일'] == '20260728'
    # 예전 호출부(수집주체 없이 부르는 곳)도 그대로 살아 있어야 합니다
    옛칸 = emit.market_entry('stocks_US.json', 300, 110, '', '2026-07-28 19:13', '20260728')
    assert 옛칸['수집주체'] == ''
