def test_종목_필드값까지_같다(실행결과, 정답지, 전략id, 시장):
    """정답지에 있는 필드는 값 하나까지 일치해야 한다.

    7/15 정답지 4종은 옛 대시보드가 `미네르비니` · `거래량비` · `순익성장률` 을 아직
    담지 않던 시절에 만들어졌습니다. 그래서 **정답지에 있는 키만** 비교합니다
    (새 엔진이 필드를 더 담는 것은 화면에 정보가 느는 것이라 문제가 아닙니다).
    """
    기대블록 = 정답지[전략id]['시장'][시장]['섹터별']
    실제블록 = 실행결과[전략id]['시장'][시장]['섹터별']
    assert len(실제블록) == len(기대블록)

    차이 = []
    for be, bg in zip(기대블록, 실제블록):
        assert len(bg['종목']) == len(be['종목'])
        for se, sg in zip(be['종목'], bg['종목']):
            for 키, 값 in se.items():
                if sg.get(키) != 값:
                    차이.append(f"{be['섹터']}/{se['티커']}.{키}: 기대 {값!r} ≠ 실제 {sg.get(키)!r}")
    assert not 차이, '\n'.join(차이)


