def test_마법공식_순위합이_규칙대로다(스냅샷원본):
    """`마법공식점수 = -(이익수익률순위 + ROE순위)`, 순위 없는 종목은 N(평가 종목 수)."""
    준비 = S.시장준비(스냅샷원본['20260716']['한국'])
    전체 = [r for 행 in 준비['섹터'].values() for r in 행]
    S.마법공식부여(전체)

    N = len(전체)
    per있음 = sorted((r for r in 전체 if S._수(S.지표(r, 'PER'), 0) > 0),
                    key=lambda r: S.지표(r, 'PER'))
    roe있음 = sorted((r for r in 전체 if S.지표(r, 'ROE') is not None),
                    key=lambda r: -S.지표(r, 'ROE'))
    이익순위 = {id(r): i + 1 for i, r in enumerate(per있음)}
    roe순위 = {id(r): i + 1 for i, r in enumerate(roe있음)}

    for r in 전체:
        합 = 이익순위.get(id(r), N) + roe순위.get(id(r), N)
        assert r['마법공식순위합'] == 합
        assert r['마법공식점수'] == -합
    # PER 이 없거나 0 이하면 이익수익률 순위에서 빠지고 N 을 받는다
    빠진것 = [r for r in 전체 if id(r) not in 이익순위]
    for r in 빠진것:
        assert S._수(S.지표(r, 'PER'), 0) <= 0


