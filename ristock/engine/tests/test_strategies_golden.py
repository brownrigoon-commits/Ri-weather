# 7. 시장준비 — 평가 종목만, 순서 그대로
# ---------------------------------------------------------------------
@pytest.mark.parametrize('기준일,시장', [(d, m) for d in ('20260715', '20260716')
                                        for m in ('한국', '미국')])
def test_시장준비는_평가종목만_원래순서로_담는다(스냅샷원본, 기준일, 시장):
    스냅 = 스냅샷원본[기준일][시장]
    준비 = S.시장준비(스냅)
    담긴티커 = [r['티커'] for 행 in 준비['섹터'].values() for r in 행]
    평가티커 = [r['티커'] for r in 스냅['종목'] if r['평가']]

    assert sorted(담긴티커) == sorted(평가티커)
    # 섹터 안의 순서 = 원본 배열 안에서의 순서 (섹터별 → 총점 내림차순)
    for 섹터, 행 in 준비['섹터'].items():
        원본순서 = [r['티커'] for r in 스냅['종목'] if r['평가'] and r['섹터'] == 섹터]
        assert [r['티커'] for r in 행] == 원본순서
        # 시트 순서는 총점 내림차순이지만, JSON 의 총점은 가중치로 **다시 계산한** 값이라
        # 반올림 한 칸(0.1) 차이로 뒤집혀 보이는 인접 쌍이 네 스냅샷 449쌍 중 10쌍 있습니다.
        # 그 이상 어긋나면 정렬이 진짜로 깨진 것입니다.
        점수들 = [r['총점'] for r in 행]
        for 앞, 뒤 in zip(점수들, 점수들[1:]):
            assert 뒤 <= 앞 + 0.1 + 1e-9, f'{섹터}: {앞} 다음에 {뒤} — 총점 내림차순이 깨짐'
    assert 준비['파일'] == 스냅['원본']
    assert 준비['수정시각'] == 스냅['생성시각']


