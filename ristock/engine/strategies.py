# 1. 필터 (설계서 3.1) — 모두 AND
# =========================================================================
def 통과여부(종목, 필터):
    """설계서 3.1 표 그대로. 필터 값이 거짓이면 그 조건은 검사하지 않습니다.

    | 키 | 통과 조건 |
    |---|---|
    | 악재제외       | `악재` 가 빈 문자열 |
    | 흑자만         | `근거.재무` 에 '흑자' 포함 |
    | 눌림만         | `근거.차트` 에 '눌림' 포함 그리고 '미눌림' 으로 시작하지 않음 |
    | 전고점돌파만   | `지표.고점대비` >= 85 그리고 `지표.10일고점비` > 0 (하나라도 null 이면 탈락) |
    | 미네르비니만   | `미네르비니` == 'O' |
    | 거래량150이상  | `지표.거래량비` >= 150 (null 은 0 으로 보아 탈락) |
    | 순익성장25이상 | `지표.순익성장률` >= 25 (null 은 탈락) |
    | 신고가근접만   | `지표.고점대비` >= 75 (null 이면 탈락) |
    """
    필터 = 필터 or {}

    if 필터.get('악재제외') and (종목.get('악재') or '').strip():
        return False

    if 필터.get('흑자만') and '흑자' not in str(근거(종목, '재무')):
        return False

    if 필터.get('눌림만'):
        차트 = str(근거(종목, '차트'))
        if '눌림' not in 차트 or 차트.startswith('미눌림'):
            return False

    if 필터.get('전고점돌파만'):
        # 전고점 돌파 = 52주 고점권(85%↑) + 최근 10일 고점을 넘어 상승 중
        위치, 등락 = 고점대비(종목), 십일고점비(종목)
        if 위치 is None or 위치 < 85:
            return False
        if 등락 is None or 등락 <= 0:
            return False

    if 필터.get('미네르비니만') and 종목.get('미네르비니') != 'O':
        return False

    if 필터.get('거래량150이상') and _수(지표(종목, '거래량비'), 0) < 150:
        # 옛 코드의 `(rec.get('거래량비(%)') or 0) < 150` — 0 도 null 도 탈락
        return False

    if 필터.get('순익성장25이상'):
        성장 = 지표(종목, '순익성장률')
        if (성장 if 성장 is not None else -999) < 25:
            return False

    if 필터.get('신고가근접만'):
        위치 = 고점대비(종목)
        if 위치 is None or 위치 < 75:
            return False

    return True


pass_filters = 통과여부          # 옛 이름 호환


