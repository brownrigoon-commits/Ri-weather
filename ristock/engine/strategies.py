# 3. 정렬 (설계서 3.2)
# =========================================================================
def 정렬(행목록, 순위기준):
    """설계서 3.2 — 모두 내림차순, null 은 0, **동점이면 입력 순서 유지(안정 정렬)**.

    파이썬 `list.sort(reverse=True)` 는 동점 원소의 상대 순서를 뒤집지 않으므로
    옛 코드와 정확히 같은 결과를 냅니다.
    """
    행 = list(행목록)
    if 순위기준 == '전고점':
        행.sort(key=lambda r: (_수(고점대비(r), 0), _수(십일고점비(r), 0),
                               _수(r.get('총점'), 0)), reverse=True)
    elif 순위기준 == '마법공식':
        행.sort(key=lambda r: (_수(r.get('마법공식점수'), -9999),
                               _수(r.get('총점'), 0)), reverse=True)
    elif 순위기준 == '총점':
        행.sort(key=lambda r: (_수(r.get('총점'), 0), _수(r.get('총점'), 0)),
                reverse=True)
    else:
        항목 = 순위기준
        행.sort(key=lambda r: (_수(점수(r, 항목), 0), _수(r.get('총점'), 0)),
                reverse=True)
    return 행


def 기준점수(종목, 순위기준):
    """화면에 보여 줄 '이 전략이 무엇을 보고 뽑았는지' 값. 옛 코드와 동일."""
    if 순위기준 == '전고점':
        return 고점대비(종목)
    if 순위기준 == '마법공식':
        return 종목.get('마법공식순위합')
    if 순위기준 == '총점':
        return 종목.get('총점')
    return 점수(종목, 순위기준)


# =========================================================================
# 4. 종목 선정 (설계서 3.3)
# =========================================================================
def _추출항목(종목, 순위기준):
    """정답지(옛 캐시)와 같은 필드 구성. 호재는 120자로 자릅니다."""
    return {
        '티커': str(종목.get('티커') or ''),
        '기업명': 종목.get('기업명') or '',
        '한글명': 종목.get('한글명') or '',
        '시총순위': 종목.get('시총순위'),
        '총점': 종목.get('총점'),
        '기준점수': 기준점수(종목, 순위기준),
        '미네르비니': 근거(종목, '미네르비니'),
        '거래량비': 지표(종목, '거래량비'),
        '순익성장률': 지표(종목, '순익성장률'),
        '모멘텀': 근거(종목, '모멘텀'),
        '차트': 근거(종목, '차트'),
        '밸류': 근거(종목, '밸류'),
        '재무': 근거(종목, '재무'),
        '수급': 근거(종목, '수급'),
        '호재': (종목.get('호재') or '')[:120],
    }


def 종목선정(섹터별, 원하는섹터, 순위기준, 필터, 개수=종목수기본, 최대=최대블록):
    """설계서 3.3.

    1. 뉴스 섹터를 순서대로 훑으며
    2. `섹터매핑[뉴스섹터]` 후보 중 **아직 안 쓴 + 필터 통과 종목이 하나라도 있는**
       첫 섹터를 고르고
    3. 그 섹터에서 필터 통과 종목을 `순위기준` 으로 정렬해 상위 `개수` 종목
    4. 최대 `최대`(3) 블록까지 만들고 멈춥니다.

    `섹터별`  : {기업분석섹터: [종목레코드…]} — `시장준비()` 산출물의 '섹터'
    `원하는섹터`: [(뉴스섹터, [후보섹터…]), …]
    """
    결과 = []
    사용됨 = set()                       # 같은 기업분석 섹터가 두 번 뽑히지 않도록
    for 뉴스섹터, 후보목록 in 원하는섹터:
        선택 = None
        for 후보 in 후보목록:
            if 후보 in 사용됨:
                continue
            if 후보 in 섹터별 and any(통과여부(r, 필터) for r in 섹터별[후보]):
                선택 = 후보
                break
        if 선택 is None:
            continue
        사용됨.add(선택)
        행 = 정렬([r for r in 섹터별[선택] if 통과여부(r, 필터)], 순위기준)
        결과.append({'뉴스섹터': 뉴스섹터, '섹터': 선택,
                     '종목': [_추출항목(r, 순위기준) for r in 행[:개수]]})
        if len(결과) >= 최대:
            break
    return 결과


pick_stocks = 종목선정            # 옛 이름 호환


