# 만듭니다. 이름이 겹치지 않도록 여기 둡니다. openpyxl 은 필요할 때만 import 합니다.

_열목록 = ['섹터', '뉴스섹터', '순위', '티커', '기업명', '한글명', '시총순위', '총점(100)',
          '모멘텀', '차트', '밸류', '재무', '수급', '호재요약']


def export_picks_xlsx(결과, 시장요약, 저장경로=None):
    """전략 추출 결과를 xlsx 로. 저장경로를 주면 파일로 쓰고, 없으면 BytesIO 를 돌려줍니다.

    시트: 시장요약 / 한국_추출종목 / 미국_추출종목 / 안내
    """
    from io import BytesIO

    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    글꼴_머리 = Font(name='맑은 고딕', size=10, bold=True, color='FFFFFF')
    글꼴_본문 = Font(name='맑은 고딕', size=10)
    글꼴_제목 = Font(name='맑은 고딕', size=11, bold=True, color='1F4E79')
    채움_머리 = PatternFill('solid', fgColor='1F4E79')

    def 행쓰기(ws, row, vals, 머리=False):
        for j, v in enumerate(vals, 1):
            c = ws.cell(row=row, column=j, value=v)
            c.font = 글꼴_머리 if 머리 else 글꼴_본문
            if 머리:
                c.fill = 채움_머리
                c.alignment = Alignment(horizontal='center')

    시장요약 = 시장요약 or {}
    wb = Workbook()

    # ---- 시트1: 시장요약 ----
    ws = wb.active
    ws.title = '시장요약'
    ws.cell(row=1, column=1,
            value=f"오늘 시장 요약  (기준 {시장요약.get('날짜', '-')})").font = 글꼴_제목
    ws.cell(row=2, column=1, value=시장요약.get('요약', '')).font = 글꼴_본문
    행쓰기(ws, 4, ['순위', '섹터', '점수', '뉴스수', '긍정', '부정'], 머리=True)
    r = 5
    for s in (시장요약.get('섹터순위') or [])[:10]:
        행쓰기(ws, r, [s['순위'], s['섹터'], s['점수'], s['뉴스수'], s['긍정'], s['부정']])
        r += 1
    for col, w in zip('ABCDEF', [6, 18, 8, 8, 8, 8]):
        ws.column_dimensions[col].width = w

    # ---- 시트2·3: 시장별 추출 종목 ----
    for 시장 in 시장이름:
        m = (결과.get('시장') or {}).get(시장) or {}
        ws2 = wb.create_sheet(f'{시장}_추출종목')
        ws2.cell(row=1, column=1,
                 value=f"{결과['전략']['name']} — {시장}"
                       f"  (데이터: {m.get('파일', '-')}, 기준 {결과.get('기준날짜', '-')})"
                 ).font = 글꼴_제목
        행쓰기(ws2, 3, _열목록, 머리=True)
        r = 4
        for 블록 in m.get('섹터별') or []:
            for i, st in enumerate(블록['종목'], 1):
                행쓰기(ws2, r, [블록['섹터'], 블록['뉴스섹터'], i, st['티커'],
                              st['기업명'], st['한글명'], st['시총순위'], st['총점'],
                              st['모멘텀'], st['차트'], st['밸류'], st['재무'],
                              st['수급'], st['호재']])
                r += 1
        for j, w in enumerate([14, 14, 6, 10, 24, 16, 9, 10, 18, 30, 18, 16, 22, 50], 1):
            ws2.column_dimensions[ws2.cell(row=3, column=j).column_letter].width = w

    # ---- 시트4: 안내 ----
    ws3 = wb.create_sheet('안내')
    안내 = [
        '본 자료는 종목 스크리닝 참고자료일 뿐 투자 권유가 아닙니다.',
        '투자 판단과 책임은 이용자 본인에게 있습니다.',
        f"전략: {결과['전략']['name']} — {결과['전략'].get('desc', '')}",
        '섹터는 오늘 10개국 뉴스에서 호재가 몰린 상위 섹터로 자동 선정됩니다.',
    ]
    for i, t in enumerate(안내, 1):
        ws3.cell(row=i, column=1, value=t).font = 글꼴_본문
    ws3.column_dimensions['A'].width = 100

    if 저장경로:
        import os
        디렉터리 = os.path.dirname(os.path.abspath(저장경로))
        if 디렉터리:
            os.makedirs(디렉터리, exist_ok=True)
        wb.save(저장경로)
        return 저장경로

    buf = BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf
