def _선정목록(전략결과, 시장):
    """전략 결과 → [(티커, {티커, 기업명, 섹터}), …] 블록 순서 · 종목 순서 그대로."""
    m = (전략결과 or {}).get('시장', {}).get(시장) or {}
    항목 = []
    for 블록 in m.get('섹터별') or []:
        for 종목 in 블록.get('종목') or []:
            항목.append((종목.get('티커'), {'티커': 종목.get('티커'),
                                           '기업명': 종목.get('기업명') or '',
                                           '섹터': 블록.get('섹터') or ''}))
    return 항목


def _전략맵(결과들):
    """dict / list / None 을 모두 `{전략id: 결과}` 로 맞춥니다."""
    if not 결과들:
        return OrderedDict()
    if isinstance(결과들, dict):
        return OrderedDict(결과들)
    맵 = OrderedDict()
    for r in 결과들:
        전략 = (r or {}).get('전략') or {}
        맵[전략.get('id') or 전략.get('name')] = r
    return 맵


def 변화계산(오늘결과, 어제결과, 기준일='', 이전기준일=''):
    """어제와 견줘 새로 들어온 종목 · 빠진 종목을 뽑습니다 (설계서 2.5).

        {"기준일": "20260716", "이전기준일": "20260715",
         "전략별": {"total": {"한국": {"신규": [{티커,기업명,섹터}], "이탈": [...]}}}}

    - 비교는 **티커 집합**으로 합니다. 같은 종목이 다른 섹터 블록으로 옮겨간 것은
      신규·이탈이 아닙니다(화면이 시끄러워지지 않게).
    - 첫 실행이라 어제 결과가 없으면 `전략별` 은 빈 객체입니다.
      "전부 신규"로 표시하면 첫날 화면이 통째로 새 종목처럼 보이기 때문입니다.
    - 어제에만 있던 전략(정의가 지워진 전략)은 비교하지 않습니다.
    """
    오늘 = _전략맵(오늘결과)
    어제 = _전략맵(어제결과)

    전략별 = OrderedDict()
    if 어제:
        for 전략id, 오늘전략 in 오늘.items():
            어제전략 = 어제.get(전략id)
            if 어제전략 is None:
                continue                      # 어제 없던 전략은 비교 대상 아님
            시장별 = OrderedDict()
            for 시장 in 시장이름:
                오늘목록 = _선정목록(오늘전략, 시장)
                어제목록 = _선정목록(어제전략, 시장)
                오늘티커 = {t for t, _ in 오늘목록}
                어제티커 = {t for t, _ in 어제목록}
                시장별[시장] = {
                    '신규': [정보 for t, 정보 in 오늘목록 if t not in 어제티커],
                    '이탈': [정보 for t, 정보 in 어제목록 if t not in 오늘티커],
                }
            전략별[전략id] = 시장별

    return {'기준일': 기준일, '이전기준일': 이전기준일 if 어제 else '',
            '전략별': 전략별}


