# 0. 종목 레코드 읽기 도우미 (설계서 2.2)
# =========================================================================
def 지표(종목, 이름):
    """`지표.<이름>` — 없으면 None. 평가 안 된 종목도 안전하게 읽힙니다."""
    return (종목.get('지표') or {}).get(이름)


def 근거(종목, 이름):
    """`근거.<이름>` — 없으면 빈 문자열. 화면 표시 전용 문장입니다."""
    return (종목.get('근거') or {}).get(이름) or ''


def 점수(종목, 이름):
    """`점수.<항목>` — 없으면 None."""
    return (종목.get('점수') or {}).get(이름)


def 고점대비(종목):
    """52주 고점 대비 위치(%). 옛 `high_position()` 이 문장에서 뽑던 값의 숫자판."""
    return 지표(종목, '고점대비')


def 십일고점비(종목):
    """최근 10일 고점 대비 등락(%). 양수면 신고가 경신 중. 옛 `dd10()` 의 숫자판."""
    return 지표(종목, '10일고점비')


def _수(값, 기본=0):
    """None → 기본값. 옛 코드의 `(x or 0)` 관용구를 그대로 옮긴 것입니다."""
    return 기본 if 값 is None else 값


