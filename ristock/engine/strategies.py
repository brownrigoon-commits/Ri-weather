# 6. 전략 실행
# =========================================================================
def 전략실행(전략, 시장데이터, 시장요약, 섹터매핑, 개수=None):
    """전략 하나를 한국·미국 양쪽에 돌립니다. 옛 `run_strategy` 와 같은 출력 구조.

    `전략`      : strategies.json 의 전략 하나 {id, name, rank_by, filters, …}
    `시장데이터`: {'한국': 시장준비(...), '미국': 시장준비(...)}  — 없으면 오류 블록
    `시장요약`  : market.json
    `섹터매핑`  : {'한국': {뉴스섹터: [기업분석섹터…]}, '미국': {…}}

    반환:
        {'전략': …, '기준날짜': …, '뉴스섹터': [상위 5], '시장': {'한국': {…}, '미국': {…}}}
    """
    순위 = 뉴스섹터순위(시장요약)
    n = int(전략.get('stocks_per_sector', 개수 if 개수 is not None else 종목수기본))
    순위기준 = 전략.get('rank_by', '총점')
    필터 = 전략.get('filters', {})

    결과 = {'전략': 전략, '기준날짜': (시장요약 or {}).get('날짜', ''),
            '뉴스섹터': 순위[:5], '시장': {}}

    for 시장 in 시장이름:
        데이터 = (시장데이터 or {}).get(시장)
        if not 데이터:
            결과['시장'][시장] = {'오류': '기업분석표 파일 없음 — 기업분석표 재생성을 먼저 실행하세요'}
            continue
        if 순위기준 == '마법공식':
            마법공식부여([r for 행 in 데이터['섹터'].values() for r in 행])
        원하는 = [(ns, (섹터매핑 or {}).get(시장, {}).get(ns, [])) for ns in 순위]
        블록 = 종목선정(데이터['섹터'], 원하는, 순위기준, 필터, n)
        결과['시장'][시장] = {'파일': 데이터.get('파일', ''),
                             '수정시각': 데이터.get('수정시각', ''),
                             '섹터별': 블록}
    return 결과


run_strategy = 전략실행            # 옛 이름 호환


def 전체전략실행(전략목록, 시장데이터, 시장요약, 섹터매핑, 개수=None):
    """전략 8종을 한 번에. `{전략id: 전략실행결과}` 를 정의 순서대로 돌려줍니다."""
    전체 = OrderedDict()
    for 전략 in 전략목록 or []:
        전체[전략.get('id') or 전략.get('name')] = 전략실행(
            전략, 시장데이터, 시장요약, 섹터매핑, 개수)
    return 전체


