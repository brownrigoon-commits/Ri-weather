# 2. 마법공식 (설계서 3.2)
# =========================================================================
def 마법공식부여(종목목록):
    """그린블라트 마법공식 — 이익수익률(1/PER) 순위 + ROE 순위 합산.

    순위가 앞설수록 `마법공식점수` 가 큽니다(정렬용, 음수).
    대상은 넘겨받은 목록 **전체**(= 해당 시장의 평가:true 종목 전체)이고,
    순위가 없는 종목은 목록 길이 N 을 순위로 씁니다. 옛 `annotate_magic` 과 동일.

    ※ 넘겨받은 레코드에 `마법공식점수` · `마법공식순위합` 을 써 넣습니다.
       `시장준비()` 가 만든 복사본에 쓰이므로 원본 JSON 은 건드리지 않습니다.
    """
    목록 = list(종목목록)

    # 저PER = 고이익수익률. PER 이 0 이하거나 없으면 순위에서 빠짐 (옛 `(PER or 0) > 0`)
    이익수익률순 = sorted((r for r in 목록 if _수(지표(r, 'PER'), 0) > 0),
                       key=lambda r: 지표(r, 'PER'))
    ROE순 = sorted((r for r in 목록 if 지표(r, 'ROE') is not None),
                   key=lambda r: -지표(r, 'ROE'))

    이익순위 = {id(r): i + 1 for i, r in enumerate(이익수익률순)}
    ROE순위 = {id(r): i + 1 for i, r in enumerate(ROE순)}
    N = len(목록)

    for r in 목록:
        합 = 이익순위.get(id(r), N) + ROE순위.get(id(r), N)
        r['마법공식점수'] = -합
        r['마법공식순위합'] = 합
    return 목록


annotate_magic = 마법공식부여     # 옛 이름 호환


