# 5. 시장 데이터 준비 (설계서 2.2 JSON → 섹터별 묶음)
# =========================================================================
def 시장준비(스냅샷):
    """`stocks_KR.json` / `stocks_US.json` → 옛 `load_market_data()[시장]` 과 같은 모양.

        {'파일': 원본xlsx, '수정시각': 생성시각, '섹터': OrderedDict{섹터: [종목…]}}

    - **평가:true 종목만** 담습니다. 옛 대시보드가 읽던 `기업분석` 시트가 평가 종목만
      담고 있었기 때문입니다. 평가 안 된 종목은 총점·근거가 없어 전략에 쓸 수 없습니다.
    - `종목` 배열 순서(섹터별 → 총점 내림차순)를 그대로 유지합니다.
      동점 정렬이 이 순서를 보존하므로 **이 순서가 곧 정답지 재현의 조건**입니다(설계서 2.2).
    - 레코드는 얕은 복사본입니다. 마법공식 주석이 원본 JSON 을 오염시키지 않습니다.
    """
    if not 스냅샷:
        return None
    섹터별 = OrderedDict()
    for 종목 in 스냅샷.get('종목') or []:
        if not 종목.get('평가'):
            continue
        섹터별.setdefault(종목.get('섹터') or '', []).append(dict(종목))
    return {'파일': 스냅샷.get('원본') or '',
            '수정시각': 스냅샷.get('생성시각') or '',
            '기준일': 스냅샷.get('기준일') or '',
            '섹터': 섹터별}


def 뉴스섹터순위(시장요약):
    """설계서 3.3-1 — 점수 > 0 인 섹터를 순서대로. 하나도 없으면 전체 순위 그대로."""
    순위 = (시장요약 or {}).get('섹터순위') or []
    return [s['섹터'] for s in 순위 if s.get('점수', 0) > 0] or [s['섹터'] for s in 순위]


